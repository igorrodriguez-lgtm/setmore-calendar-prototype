/** Thin strokes to match Setmore's 1.5px line icons. */
const thin = (Icon: LucideIcon): KitIcon =>
  function ThinIcon({ size = "16", ...props }) {
    return createElement(Icon, { size: Number(size), strokeWidth: 1.5, ...props });
  };

